package situationsignalsworker

// page.go owns the windowing helpers shared by the two pollers: merging the
// fresh Telegram items into the cached feed, trimming the feed to maxFeedItems,
// trimming the event payload and keeping the last N OREF history waves. They
// are separated from the pollers so the merge/order semantics can be tested
// without a Telegram owner or an HTTP server.

// mergeTelegramItems mirrors the merge block of pollTelegramOnce:
//
//	fresh first, cached items second, de-duplicated by id keeping the first
//	occurrence, sorted by ts descending with a stable sort (the JavaScript sort
//	is stable), then sliced to maxFeedItems.
//
// Timestamps are ISO-8601 strings generated by both implementations, so a byte
// comparison is the same as localeCompare for every value either writer can
// produce.
func mergeTelegramItems(fresh, cached []TelegramItem, maxFeedItems int) []TelegramItem {
	merged := make([]TelegramItem, 0, len(fresh)+len(cached))
	seen := make(map[string]struct{}, len(fresh)+len(cached))
	for _, item := range fresh {
		if _, duplicate := seen[item.ID]; duplicate {
			continue
		}
		seen[item.ID] = struct{}{}
		merged = append(merged, item)
	}
	for _, item := range cached {
		if _, duplicate := seen[item.ID]; duplicate {
			continue
		}
		seen[item.ID] = struct{}{}
		merged = append(merged, item)
	}

	// Insertion sort with a stable descending comparison: the JavaScript
	// Array.prototype.sort leaves items with an equal ts in their original
	// order, and Go's sort.Slice is not guaranteed to.
	stableSortItemsByTSDesc(merged)

	if maxFeedItems >= 0 && len(merged) > maxFeedItems {
		merged = merged[:maxFeedItems]
	}
	if merged == nil {
		merged = []TelegramItem{}
	}
	return merged
}

// stableSortItemsByTSDesc sorts by descending ts while preserving the relative
// order of equal timestamps (insertion sort is stable and the feeds are small:
// at most maxFeedItems + one poll cycle worth of new items).
func stableSortItemsByTSDesc(items []TelegramItem) {
	for index := 1; index < len(items); index++ {
		current := items[index]
		position := index - 1
		for position >= 0 && items[position].TS < current.TS {
			items[position+1] = items[position]
			position--
		}
		items[position+1] = current
	}
}

// sliceTelegramItems mirrors Array.prototype.slice(0, limit) for the event
// payload (newItems.slice(0, 30)).
func sliceTelegramItems(items []TelegramItem, limit int) []TelegramItem {
	if limit < 0 {
		limit = 0
	}
	if len(items) > limit {
		items = items[:limit]
	}
	out := make([]TelegramItem, len(items))
	copy(out, items)
	return out
}

// tailHistory mirrors `history.length > maxWaves ? history.slice(-maxWaves) :
// history` from persistOrefHistory.
func tailHistory(history []OrefHistoryEntry, maxWaves int) []OrefHistoryEntry {
	if maxWaves < 0 {
		maxWaves = 0
	}
	if len(history) > maxWaves {
		history = history[len(history)-maxWaves:]
	}
	out := make([]OrefHistoryEntry, len(history))
	copy(out, history)
	return out
}
