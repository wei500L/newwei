package crawlfrontierruns

import (
	"context"
	"database/sql/driver"
	"errors"
	"net"

	mysqlDriver "github.com/go-sql-driver/mysql"
)

// statusError mirrors a NestJS HttpException. It is rendered with
// authhttp.WriteHTTPException, which reproduces the GlobalExceptionFilter REST
// shape (statusCode, message, error).
type statusError struct {
	status  int
	message string
}

// Error implements error.
func (e *statusError) Error() string { return e.message }

// newStatus builds a statusError.
func newStatus(status int, message string) error {
	return &statusError{status: status, message: message}
}

// inputError is a 400 generated by the DTO layer. Message already follows the
// class-validator + GlobalExceptionFilter joining rules ("; " between
// constraint messages) or is a service-level business sentence.
type inputError struct{ Message string }

// Error implements error.
func (e *inputError) Error() string { return e.Message }

// unavailable reports database-unavailable errors, which fail closed with the
// same 503 shape as Prisma connection errors in NestJS.
func unavailable(err error) bool {
	if err == nil {
		return false
	}
	if errors.Is(err, driver.ErrBadConn) || errors.Is(err, context.DeadlineExceeded) {
		return true
	}
	var mysqlErr *mysqlDriver.MySQLError
	if errors.As(err, &mysqlErr) {
		switch mysqlErr.Number {
		case 1040, 1042, 1043, 1053, 1159, 1160, 1161, 2002, 2003, 2006, 2013:
			return true
		}
	}
	var netErr net.Error
	return errors.As(err, &netErr)
}
