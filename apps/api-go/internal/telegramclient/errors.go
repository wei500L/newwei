package telegramclient

import (
	"strings"
	"time"

	"github.com/gotd/td/tgerr"
)

// Telegram RPC error types the worker classifies without inspecting the error
// text. gotd parses the server message into tgerr.Error.Type/Argument, so these
// comparisons keep working regardless of language or message formatting.
const (
	errorAuthKeyDuplicated   = "AUTH_KEY_DUPLICATED"
	errorUsernameNotOccupied = "USERNAME_NOT_OCCUPIED"
	errorChannelInvalid      = "CHANNEL_INVALID"
)

// IsAuthKeyDuplicated reports whether err is Telegram's AUTH_KEY_DUPLICATED.
// The NestJS service treats it as terminal for the poller: the session was
// invalidated and must be regenerated by an administrator.
//
// RPC calls return a *tgerr.Error, but gotd also surfaces the error from the
// connection layer (telegram/connect.go), where it is wrapped by
// cenkalti/backoff.Permanent. Whether errors.As unwraps that wrapper is not
// verified, so a text fallback is kept for the Run path only; the RPC path is
// still classified by type.
func IsAuthKeyDuplicated(err error) bool {
	if err == nil {
		return false
	}
	if tgerr.Is(err, errorAuthKeyDuplicated) {
		return true
	}
	return strings.Contains(err.Error(), errorAuthKeyDuplicated)
}

// IsFloodWait reports whether err is a FLOOD_WAIT or FLOOD_PREMIUM_WAIT error.
func IsFloodWait(err error) bool {
	_, ok := tgerr.AsFloodWait(err)
	return ok
}

// FloodWaitSeconds returns the FLOOD_WAIT duration in whole seconds, or 0 when
// err is not a flood-wait error.
func FloodWaitSeconds(err error) int {
	wait, ok := tgerr.AsFloodWait(err)
	if !ok {
		return 0
	}
	return int(wait / time.Second)
}

// IsUsernameNotOccupied reports whether err is USERNAME_NOT_OCCUPIED: the
// channel handle no longer exists, so the peer cache entry is stale.
func IsUsernameNotOccupied(err error) bool {
	return tgerr.Is(err, errorUsernameNotOccupied)
}

// IsChannelInvalid reports whether err is CHANNEL_INVALID: the cached access
// hash is no longer valid, so the channel must be resolved again.
func IsChannelInvalid(err error) bool {
	return tgerr.Is(err, errorChannelInvalid)
}

// ErrorDescription returns the Telegram error type text (for example
// "PHONE_CODE_INVALID") when err is a Telegram RPC error. Other errors fall
// back to err.Error(), and nil yields an empty string. The result is safe to
// log: it never contains message contents or credentials.
func ErrorDescription(err error) string {
	if err == nil {
		return ""
	}
	rpcErr, ok := tgerr.As(err)
	if !ok {
		return err.Error()
	}
	if rpcErr == nil {
		return ""
	}
	if rpcErr.Type != "" {
		return rpcErr.Type
	}
	return rpcErr.Message
}
